export function useI18n() {
  function t(key: string, params?: Record<string, string>): string {
    let val = messages[lang.value]?.[key] ?? messages.zh[key] ?? key;
    if (params) {
      for (const [k, v] of Object.entries(params)) {
        val = val.split(`{${k}}`).join(v);
      }
    }
    return val;
  }

  async function setLanguage(l: Lang) {
    lang.value = l;
    try { await setSetting('app_lang', l); } catch {}
  }

  async function initLanguage() {
    try {
      const saved = await getSetting('app_lang');
      if (saved === "zh" || saved === "en") lang.value = saved;
    } catch {}
  }

  return { lang, t, setLanguage, initLanguage };
}
